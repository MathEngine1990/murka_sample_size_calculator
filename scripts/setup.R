# Run once from the folder containing app.R.
if (.Platform$OS.type == "windows" && !l10n_info()[["UTF-8"]])
  Sys.setlocale("LC_CTYPE", ".UTF-8")
stopifnot(file.exists("app.R"), file.exists("renv.lock"))
options(repos = c(CRAN = "https://cloud.r-project.org"), timeout = 600)
lib <- file.path(getwd(), ".Rlibrary")
dir.create(lib, recursive = TRUE, showWarnings = FALSE)
.libPaths(c(lib, .libPaths()))
Sys.setenv(RENV_PATHS_CACHE = file.path(getwd(), ".renv-cache"))
if (!requireNamespace("renv", quietly = TRUE)) install.packages("renv", lib = lib)
if (packageVersion("renv") < "1.1.0") stop("Обновите renv до версии >= 1.1.0.")
renv::restore(project = getwd(), library = lib, prompt = FALSE)
stopifnot(packageVersion("shiny") >= "1.8.1")
cat("Готово. Запуск: source('scripts/run_local.R')\n")
